# ## 1. The stream and the exact answers
# 
# Each stream element is one edit; its value is the page that was edited. `page[i]` is the page id of the i-th edit, `counts[j]` is the number of edits of the j-th distinct page, and `inv[i]` says which distinct page edit i belongs to.
# 
# - **F0** = number of distinct pages.
# - **F1** = number of edits (the stream length n).
# - **F2** = sum over pages of (edits of that page) squared. It measures how uneven the stream is: F2 = n when every page is edited once, and F2 = n squared when one page gets every edit.
# 
# The exact F2 below needs one counter per distinct page. AMS estimates it with a fixed, small number of counters.

