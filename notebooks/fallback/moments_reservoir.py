# ## 2. AMS estimate of the second moment
# 
# Alon, Matias and Szegedy (1996); the form used here is the one in *Mining of Massive Datasets*, section 4.5.
# 
# ### One AMS variable
# 
# A variable stores two things: one page, and a count.
# 
# 1. Pick one position in the stream uniformly at random.
# 2. When the stream reaches that position, remember the page there and set the count `c` to 1.
# 3. For every later edit: if it is the same page, add 1 to `c`.
# 4. At the end, the estimate is `X = n * (2c - 1)`.
# 
# ### Why the average of X is F2
# 
# Take a page with m edits. Its m positions give c = m, m-1, ..., 1, so their values of 2c - 1 are the first m odd numbers, and the first m odd numbers add up to m squared. Adding over all pages, the sum of (2c - 1) over every position is F2. A random position is one of n, so the expected value of n * (2c - 1) is exactly F2: the estimate is unbiased.
# 
# ### Many variables
# 
# One variable is very noisy. Take v variables at independent positions, split them into groups, take the mean of each group, and report the median of the group means. The mean reduces the noise; the median protects against a group that hit an extreme page. Memory is v times (one page id + one count), 16 bytes each, whatever the number of distinct pages.
# 
# ### First on the textbook stream
# 
# The stream a, b, c, b, d, a, c, d, a, b, d, c, a, a, b has F2 = 59. The class below is the algorithm as it would run on a live stream: one pass, and each variable sees each element once.

# In[3]:


class AMSVariable:
    """One AMS variable: the element at one chosen position, and how often it has appeared from there on."""

    def __init__(self, position):
        self.position = position        # the randomly chosen stream position (0-based)
        self.element = None             # filled in when the stream reaches that position
        self.count = 0

    def see(self, index, element):
        if index == self.position:      # step 2: start counting here
            self.element, self.count = element, 1
        elif index > self.position and element == self.element:
            self.count += 1             # step 3: the same element again

    def estimate(self, n):
        return n * (2 * self.count - 1) # step 4


toy = list('abcbdacdabdcaab')
toy_f2 = sum(toy.count(x) ** 2 for x in set(toy))
variables = [AMSVariable(p) for p in (2, 7, 12)]          # the textbook's positions 3, 8 and 13 (it counts from 1)
for index, element in enumerate(toy):                     # one pass over the stream
    for var in variables:
        var.see(index, element)
for var in variables:
    print(f"position {var.position + 1:>2}: element {var.element}, count {var.count}, estimate {var.estimate(len(toy))}")
toy_estimates = [var.estimate(len(toy)) for var in variables]
print('exact F2:', toy_f2, '| mean of the three estimates:', sum(toy_estimates) / 3)
assert toy_f2 == 59 and toy_estimates == [75, 45, 45]     # the textbook's numbers

# one variable at every position: their mean is F2 exactly (the unbiasedness argument above)
every = [AMSVariable(p) for p in range(len(toy))]
for index, element in enumerate(toy):
    for var in every:
        var.see(index, element)
print('mean of the estimates over all', len(toy), 'positions:', sum(v_.estimate(len(toy)) for v_ in every) / len(toy))
assert sum(v_.estimate(len(toy)) for v_ in every) == toy_f2 * len(toy)


# ### Then on the real stream
# 
# Millions of Python objects would be slow, and we want to repeat the experiment over many seeds. So the next cell computes `c` for **every** position once, with array operations. The definition is the same as in the class above (it is checked against the class on the textbook stream). Drawing an AMS variable is then just picking a random position and reading its value.
# 
# The experiment: for each number of variables v, run 30 seeds, and compare the median-of-means estimate with the exact F2.

# In[4]:


def count_from_each_position(inv, counts):
    """c for every stream position: how often the page at that position appears from there to the end of the stream.

    inv[i]    = index of the distinct page of edit i
    counts[j] = total edits of distinct page j
    """
    n = len(inv)
    order = np.argsort(inv, kind='stable')                         # positions grouped by page; stream order inside a page
    group_start = np.concatenate([[0], np.cumsum(counts)[:-1]])    # where each page's group begins in `order`
    seen_before = np.empty(n, dtype=np.int64)
    seen_before[order] = np.arange(n) - np.repeat(group_start, counts)   # 0 for a page's first edit, 1 for its second, ...
    return counts[inv] - seen_before                               # all edits of the page, minus those before this one


def ams_estimate(X_all, v, rng, groups=10):
    """Median of means of v AMS variables placed at uniformly random positions."""
    positions = rng.integers(0, len(X_all), size=v)
    x = X_all[positions]
    return float(np.median([g.mean() for g in np.array_split(x, groups)]))


# check the fast version against the class on the textbook stream
_, toy_inv, toy_counts = np.unique(np.array(toy), return_inverse=True, return_counts=True)
assert list(count_from_each_position(toy_inv, toy_counts)) == [v_.count for v_ in every]

c_all = count_from_each_position(inv, counts)
X_all = n * (2.0 * c_all - 1.0)                                    # the estimate each position would give
assert abs(X_all.mean() - F2) / F2 < 1e-9                          # unbiased: the mean over all positions is F2

rows = []
SEEDS = 30
for v in (100, 300, 1000, 3000, 10000):
    errs = np.array([100 * (ams_estimate(X_all, v, np.random.default_rng(SEED + s)) - F2) / F2 for s in range(SEEDS)])
    rows.append({'variables': v, 'mean_error_pct': round(float(errs.mean()), 2), 'mean_abs_error_pct': round(float(np.abs(errs).mean()), 2),
                 'worst_abs_error_pct': round(float(np.abs(errs).max()), 2), 'memory_bytes': v * 16})
ams = pd.DataFrame(rows)
ams


# **Reading the table.** Each row is 30 runs with different random positions. `mean_error_pct` is the average signed error (negative = too low), `mean_abs_error_pct` the average size of the error, `worst_abs_error_pct` the worst of the 30 runs.
# 
# Edits per page are heavy-tailed (a few pages carry a large share of F2), so the median of means sits below F2 until the sample is large enough to hit those pages. The estimator is unbiased for the mean; the median step trades that for stability, which is why the signed error is negative for small v.
# 
# On a live stream the length n is not known in advance. The positions are then kept with reservoir sampling, which is the next section.

# ## 3. Reservoir sampling (Algorithm L)

# In[5]:


def reservoir_positions(n, k, rng):
    """Positions of a uniform sample of k items from a stream of n, in one pass with k slots (Li's Algorithm L)."""
    res = np.arange(k)
    w = math.exp(math.log(rng.random()) / k)
    i = k - 1
    while True:
        i += int(math.log(rng.random()) / math.log(1.0 - w)) + 1
        if i >= n:
            return res
        res[rng.integers(0, k)] = i
        w *= math.exp(math.log(rng.random()) / k)

p_true = float(is_revert.mean())
rows = []
RUNS_PER_K = 200
for k in (1000, 10000, 100000):
    est, pos = [], []
    for s in range(RUNS_PER_K):
        idx = reservoir_positions(n, k, np.random.default_rng(SEED + s))
        est.append(is_revert[idx].mean()); pos.append(idx.mean() / n)
    est = np.array(est)
    se = math.sqrt(p_true * (1 - p_true) / k)
    rows.append({'sample_size': k, 'exact_share_pct': round(100 * p_true, 3), 'mean_estimate_pct': round(100 * float(est.mean()), 3),
                 'sd_of_estimates_points': round(100 * float(est.std(ddof=1)), 3), 'binomial_se_points': round(100 * se, 3),
                 'within_2_se_pct': round(100 * float((np.abs(est - p_true) <= 2 * se).mean()), 1),
                 'mean_relative_position': round(float(np.mean(pos)), 3)})
res = pd.DataFrame(rows)
res


# The spread of the estimates matches the binomial standard error, and the sampled positions are centered on the middle of the stream: the reservoir is a uniform sample although it never knew the stream length.

