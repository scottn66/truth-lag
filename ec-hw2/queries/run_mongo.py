def run_pipeline(db, coll: str, pipeline: list, allow_disk: bool) -> list[dict]:
    kw = {"allowDiskUse": True} if allow_disk else {}
    return list(db[coll].aggregate(pipeline, **kw))


def timed(db, coll: str, pipeline: list, runs: int, allow_disk: bool):
    """Median of `runs` warm runs after 1 warm-up (runs=1: one run, no warm-up)."""
    if runs > 1:
        run_pipeline(db, coll, pipeline, allow_disk)
    times, out = [], None
    for _ in range(runs):
        t = time.perf_counter()
        out = run_pipeline(db, coll, pipeline, allow_disk)
        times.append((time.perf_counter() - t) * 1000)
    return out, {"median_ms": round(statistics.median(times), 1),
                 "min_ms": round(min(times), 1), "max_ms": round(max(times), 1), "runs": runs}


def wilson(k: int, n: int, z: float = Z95):
    """Wilson score interval for k successes in n trials."""
    if n == 0:
        return None, None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def decile_rows(result: list[dict]) -> list[dict]:
    scored = sorted((g for g in result if isinstance(g["_id"], dict)), key=lambda g: g["_id"]["min"])
    rows = []
    for i, g in enumerate(scored, start=1):
        rows.append(("decile %d" % i, i, g["_id"]["min"], g["_id"]["max"], g))
    for g in result:
        if g["_id"] == "no score":
            rows.append(("no score", None, None, None, g))
    out = []
    for label, num, lo, hi, g in rows:
        if g["n"] < config.RISK_MIN_GROUP_N:
            continue
        r = {"group": label, "decile": num, "risk_min": lo, "risk_max": hi, "n": g["n"],
             "n_reverted_4d": g["n_reverted_4d"], "revert_rate_4d": g["n_reverted_4d"] / g["n"],
             "median_T_s": g["median_T_s"],
             # 'no score' = page creations + edits whose score event was not captured.
             "n_page_creations": g.get("n_page_creations", 0),
             "n_other_edits": g["n"] - g.get("n_page_creations", 0)}
        for i, name in enumerate(config.DECISION_WAITS_S):
            k, n = g[f"event_{i}"], g[f"at_risk_{i}"]
            lo_ci, hi_ci = wilson(k, n)
            tag = name.replace(" ", "")
            r[f"at_risk_{tag}"] = n
            r[f"reverted_after_{tag}"] = k
            r[f"p_{tag}"] = k / n if n else None
            r[f"ci_lo_{tag}"] = lo_ci
            r[f"ci_hi_{tag}"] = hi_ci
        out.append(r)
    return out


