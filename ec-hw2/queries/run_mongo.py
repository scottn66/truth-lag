def page_titles() -> dict:
    rev = pd.read_parquet(bd.TABLE_FILES["history_revisions"], columns=["page_id", "page_title", "ts"])
    rev = rev.sort_values("ts").dropna(subset=["page_title"]).drop_duplicates("page_id", keep="last")
    return dict(zip(rev["page_id"], rev["page_title"]))


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Run Mongo Q1-Q5 and the comparison query.")
    p.add_argument("--target", choices=["local", "atlas"], default="local")
    p.add_argument("--runs", type=int, default=7, help="timed warm runs (after 1 warm-up)")
    args = p.parse_args(argv)
    bd.check_inputs(["history_revisions", "history_revert_links", "live_revisions",
                     "live_revert_links"])
    local = args.target == "local"
    if local:
        db = connect(config.MONGO_URI)[config.MONGO_DB]
        prefix = "mongo_"
    else:
        if not config.ATLAS_URI:
            raise SystemExit("STOP: ATLAS_URI is empty. Put it in ec-hw2/.env.")
        db = connect(config.ATLAS_URI, 15000)[config.ATLAS_DB]
        prefix = "mongo_atlas_"
    cohorts = sorted(db[config.COL_REVISIONS].distinct("cohort"))
    if not cohorts:
        raise SystemExit("STOP: the revisions collection is empty. Run load_mongo.py first.")
    if local and db[config.COL_PAGE_HOUR].estimated_document_count() == 0:
        raise SystemExit("STOP: page_hour is empty. Run speed_layer.py first (Mongo Q5 reads it).")
    print(f"target {args.target}: cohorts in the database: {', '.join(cohorts)}")

    config.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    paths = write_query_files()
    specs = {name: load_query(path) for name, path in paths.items()}

    results, timings, tables = {}, {}, {}
    for name in QUERIES:
        spec = specs[name]
        out, t = timed(db, spec["collection"], spec["pipeline"], args.runs, local)
        results[name], timings[name] = out, t
        print(f"{name:28s} {len(out):>6,} result documents  median {t['median_ms']:>9,.1f} ms "
              f"(min {t['min_ms']:,.1f}, max {t['max_ms']:,.1f}, runs {t['runs']})")

    dec_spec = specs["q5_risk_deciles"]
    dec_out, dec_t = timed(db, dec_spec["collection"], dec_spec["pipeline"], 1, local)
    deciles = decile_rows(dec_out) if L in cohorts else []
    timings["q5_risk_deciles"] = dec_t
    print(f"{'q5_risk_deciles':28s} {len(deciles):>6,} groups            "
          f"one run {dec_t['median_ms']:,.1f} ms")

    titles = page_titles()
    for name, out in results.items():
        for suffix, df in flatten(name, out).items():
            if name == "compare_mutual_reverts":
                tables["mutual_raw"] = df
                df = pseudonymize_pairs(df, titles) if len(df) else df
            tables[name + suffix] = df
            write_table(df, f"{prefix}{name}{suffix}", TITLES[name] + (
                " - page activity before the edit" if suffix else ""),
                specs[name]["description"], timings[name] if not suffix else None)
    if deciles:
        dfd = pd.DataFrame(deciles)
        tables["q5_risk_deciles"] = dfd
        write_table(dfd, f"{prefix}q5_risk_deciles", "Mongo Q5: live revert-risk deciles",
                    dec_spec["description"], dec_t)

    checks = [check_q1(tables["q1_revert_rate_by_hour"], cohorts),
              check_q2(tables["q2_top_contested_pages"]),
              *check_q3(tables["q3_time_to_revert"], cohorts),
              check_q5(tables["q5_truth_lag_preview"], cohorts),
              check_mutual(tables["mutual_raw"], aliased=not local),
              check_no_editor_identity({k: v for k, v in tables.items() if k != "mutual_raw"})]
    if deciles:
        print("Q5 risk deciles check:")
        checks.append(check_deciles(deciles))
    charts = write_charts(db, specs, deciles, local) if local else {}
    if charts:
        print("chart collections:", ", ".join(f"{k}={v}" for k, v in charts.items()))

    summary = pd.DataFrame([{"query": n, "collection": specs[n]["collection"] if n in specs else
                             config.COL_REVISIONS, "result_rows": len(tables.get(n, [])) if n in tables
                             else len(results.get(n, [])), **t} for n, t in timings.items()])
    write_table(summary, f"{prefix}summary", "MongoDB query timings",
                f"Target: {args.target}. MongoDB {db.client.server_info()['version']}. "
                + (f"Each query ran {args.runs} warm times after 1 warm-up; median_ms is the "
                   "median of those runs. " if args.runs > 1 else
                   "Each query ran once (no warm-up): a quick check, not a timing. ")
                + "The risk deciles ran once. Checks: "
                + "; ".join(f"{c['name']}: {'OK' if c['ok'] else 'DIFFERENT'}" for c in checks)
                + ".", None)
    rows = {f"{prefix}{k}.csv": len(v) for k, v in tables.items() if k != "mutual_raw"}
    bd.write_success("mongo_queries" if local else "mongo_atlas_queries", rows, config.RESULTS_DIR,
                     {"target": args.target, "checks": checks, "charts": charts})
    print("checks:")
    for c in checks:
        print(f"  {'OK       ' if c['ok'] else 'DIFFERENT'} {c['name']}")
    if not all(c["ok"] for c in checks):
        print("SOME CHECKS FAILED")
        return 1
    return 0


