LINE_WIDTH = 100


def _compact(obj) -> str:
    return json_util.dumps(obj, json_options=json_util.RELAXED_JSON_OPTIONS,
                           separators=(", ", ": "))


def _pretty(obj, indent: int, col: int | None = None) -> str:
    """Extended JSON where any part that fits in LINE_WIDTH stays on one line.

    One token per line (plain indent=2) would make the pipelines look 3-4 times
    longer than they are, which is unfair in the lines-of-code comparison.
    indent = the indent of the line; col = the column where this value starts.
    """
    col = indent if col is None else col
    one = _compact(obj)
    if not isinstance(obj, (dict, list)) or not obj or col + len(one) <= LINE_WIDTH:
        return one
    pad, inner = " " * indent, " " * (indent + 2)
    if isinstance(obj, dict):
        items = []
        for k, v in obj.items():
            key = json.dumps(k)
            items.append(f"{inner}{key}: {_pretty(v, indent + 2, indent + 4 + len(key))}")
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    items = [inner + _pretty(v, indent + 2) for v in obj]
    return "[\n" + ",\n".join(items) + "\n" + pad + "]"


def dumps(obj) -> str:
    return _pretty(obj, 0) + "\n"


