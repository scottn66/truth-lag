def _exact_median(list_field: str, out_field: str) -> list[dict]:
    """Exact median of a pushed list ($median in MongoDB 8.0 is approximate only).

    Same rule as pandas: the middle value, or the mean of the two middle values.
    """
    s, n = "$_sorted", "$_n"
    half = {"$toInt": {"$floor": {"$divide": [n, 2]}}}
    return [
        {"$addFields": {"_sorted": {"$sortArray": {"input": {"$filter": {
            "input": f"${list_field}", "cond": {"$ne": ["$$this", None]}}}, "sortBy": 1}}}},
        {"$addFields": {"_n": {"$size": s}}},
        {"$addFields": {out_field: {"$switch": {"branches": [
            {"case": {"$eq": [n, 0]}, "then": None},
            {"case": {"$eq": [{"$mod": [n, 2]}, 1]}, "then": {"$arrayElemAt": [s, half]}}],
            "default": {"$avg": [{"$arrayElemAt": [s, {"$subtract": [half, 1]}]},
                                 {"$arrayElemAt": [s, half]}]}}}}},
        {"$project": {"_sorted": 0, "_n": 0, list_field: 0}},
    ]


# A page creation has parent_id 0 (null is treated the same way). It never gets a score.
_CREATION = {"$eq": [{"$ifNull": ["$parent_id", 0]}, 0]}


def risk_deciles_pipeline() -> list[dict]:
    """Live revert-risk deciles ($bucketAuto) plus a 'no score' group."""
    out = {"n": {"$sum": 1}, "n_reverted_4d": {"$sum": {"$cond": ["$rev_4d", 1, 0]}},
           "n_page_creations": {"$sum": {"$cond": ["$creation", 1, 0]}},
           "T_list": {"$push": "$T_rev"}}
    for i, w in enumerate(config.DECISION_WAITS_S.values()):
        out[f"at_risk_{i}"] = {"$sum": {"$cond": [{"$gt": ["$T_inf", w]}, 1, 0]}}
        out[f"event_{i}"] = {"$sum": {"$cond": [
            {"$and": ["$rev_4d", {"$gt": ["$T_inf", w]}]}, 1, 0]}}
    # An edit that is never reverted has T = infinity: it is always still "at risk".
    # Only the needed fields go into the sort of $bucketAuto. No $facet here: in
    # MongoDB 8.0.34 a $bucketAuto with $push inside a $facet fails when its sort
    # spills to disk ("duplicate input position"), so the 'no score' group is added
    # with $unionWith instead.
    lean = [{"$project": {"risk": 1, "rev_4d": 1, "creation": 1, "T_inf": {"$ifNull": ["$T", 1e18]},
                          "T_rev": {"$cond": ["$rev_4d", "$T", None]}}}]
    creation = {"creation": _CREATION}
    no_score = (_q5_prepared([L], {"live.revert_risk": None}, creation) + lean
                + [{"$group": {"_id": "no score", **out}}, *_exact_median("T_list", "median_T_s")])
    return (_q5_prepared([L], {"live.revert_risk": {"$ne": None}}, creation) + lean
            + [{"$bucketAuto": {"groupBy": "$risk", "buckets": config.RISK_DECILES, "output": out}},
               *_exact_median("T_list", "median_T_s"),
               {"$unionWith": {"coll": config.COL_REVISIONS, "pipeline": no_score}}])


def q5_risk_deciles() -> dict:
    """Mongo Q5, second part: the live cohort grouped by the revert-risk score."""
    waits = list(config.DECISION_WAITS_S)
    desc = ("Mongo Q5 (spec 3.5), risk deciles: the LIVE cohort only (Atlas holds the history "
            "cohort only, so run it on the local database). It starts from revisions with the "
            "same stages as q5_truth_lag_preview ($lookup of revert_links for T and K, and of "
            "page_hour). Edits with a Wikimedia revert-risk score at save time are split into "
            f"{config.RISK_DECILES} groups of about equal size with $bucketAuto on "
            "live.revert_risk (_id.min and _id.max are the score range; the last group includes "
            "its max). A $unionWith adds one more group, 'no score': the revisions without a "
            "score. These are page creations (they never get a score; n_page_creations) and "
            "edits whose score event was not captured (n - n_page_creations). Per group: n, "
            f"n_reverted_4d (T <= {HORIZON_S} s, self-reverts count), the exact median T of those "
            "reverts ($push + $sortArray; $median in MongoDB 8.0 is only approximate), and for "
            f"each wait w in {waits} (index 0, 1, 2): at_risk_i = edits with T > w (never "
            "reverted counts as T = infinity) and event_i = those reverted within 4 days. "
            "queries/run_mongo.py then computes p = event_i / at_risk_i, the residual "
            "P(w < T <= 4 d | T > w), with a Wilson 95% interval in Python (run_mongo.wilson), "
            f"and drops groups with n < {config.RISK_MIN_GROUP_N}. Provisional until "
            f"{config.LIVE_FINAL_AFTER.isoformat()}." + _how_to(config.COL_REVISIONS))
    return {"collection": config.COL_REVISIONS, "description": desc,
            "pipeline": risk_deciles_pipeline()}


