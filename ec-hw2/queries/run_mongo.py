def q1_revert_rate_by_hour() -> dict:
    """Spec 3.1: revert rate by hour of day (UTC) x user kind, both cohorts."""
    live_part = [
        {"$match": {"cohort": L}},
        _revert_link_lookup("link", {"within_followup": True}, fields=("T_s",)),
        {"$project": {"_id": 0, "cohort": 1, "hour_utc": 1, "user_kind": "$user.kind",
                      "reverted": {"$gt": [{"$size": "$link"}, 0]}}},
    ]
    pipeline = [
        {"$match": {"cohort": H}},
        {"$project": {"_id": 0, "cohort": 1, "hour_utc": 1, "user_kind": "$user.kind",
                      "reverted": "$history.reverted"}},
        {"$unionWith": {"coll": config.COL_REVISIONS, "pipeline": live_part}},
        {"$group": {"_id": {"cohort": "$cohort", "hour_utc": "$hour_utc",
                            "user_kind": "$user_kind"},
                    "edits": {"$sum": 1},
                    "reverted": {"$sum": {"$cond": ["$reverted", 1, 0]}}}},
        {"$project": {"_id": 0, "cohort": "$_id.cohort", "hour_utc": "$_id.hour_utc",
                      "user_kind": "$_id.user_kind", "edits": 1, "reverted": 1,
                      "revert_rate": {"$divide": ["$reverted", "$edits"]}}},
        {"$sort": {"cohort": 1, "hour_utc": 1, "user_kind": 1}},
    ]
    desc = ("Mongo Q1 (spec 3.1): the revert rate by hour of day (UTC, hour of the edit) and "
            "user kind (bot, temporary = logged out, registered, unknown), for both cohorts. "
            f"History cohort: reverted = history.reverted (reverted within "
            f"{config.HISTORY_FOLLOWUP_DAYS} days, self-reverts included). Live cohort: reverted = "
            f"a revert_links document (found with $lookup) with within_followup "
            f"(within {config.LIVE_FOLLOWUP_DAYS} days). The live half is added with $unionWith, "
            "so the $lookup runs only for live documents. Output: cohort, hour_utc, user_kind, "
            "edits, reverted, revert_rate." + _how_to(config.COL_REVISIONS))
    return {"collection": config.COL_REVISIONS, "description": desc, "pipeline": pipeline}


def q2_top_contested_pages() -> dict:
    """Spec 3.2 and the comparison query: top 20 contested pages (DATA_MODEL section 7)."""
    pipeline = [
        {"$match": {"cohort": H, "within_followup": True, "by_other": True}},
        {"$group": {"_id": "$page_id",
                    "actions": {"$addToSet": "$reverting_rev_id"},
                    "editors": {"$addToSet": "$author_key"}}},
        {"$project": {"revert_actions": {"$size": "$actions"},
                      "reverted_editors": {"$size": "$editors"}}},
        {"$match": {"reverted_editors": {"$gte": config.CONTESTED_MIN_EDITORS}}},
        {"$lookup": {"from": config.COL_REVISIONS, "localField": "_id", "foreignField": "page.id",
                     "pipeline": [
                         {"$match": {"cohort": H}},
                         {"$sort": {"ts": 1}},
                         {"$group": {"_id": None,
                                     "edits": {"$sum": {"$cond": ["$user.is_bot", 0, 1]}},
                                     "title": {"$last": "$page.title"}}}],
                     "as": "rev"}},
        {"$unwind": "$rev"},
        {"$project": {"_id": 0, "page_id": "$_id", "page_title": "$rev.title",
                      "edits": "$rev.edits", "revert_actions": 1, "reverted_editors": 1}},
        {"$match": {"edits": {"$gte": config.CONTESTED_MIN_EDITS}}},
        {"$addFields": {"score": {"$divide": ["$revert_actions", "$edits"]}}},
        {"$sort": {"score": -1, "revert_actions": -1, "edits": -1, "page_id": 1}},
        {"$limit": config.TOP_N},
        {"$addFields": {"contested": {"$and": [
            {"$gte": ["$revert_actions", config.CONTESTED_MIN_ACTIONS]},
            {"$gte": ["$reverted_editors", config.CONTESTED_MIN_EDITORS]},
            {"$gte": ["$score", config.CONTESTED_MIN_SCORE]}]}}},
    ]
    desc = (f"Mongo Q2 (spec 3.2), also the 'top contested pages' comparison query: the top "
            f"{config.TOP_N} contested pages of the history cohort, with the shared definition of "
            "DATA_MODEL.md section 7. revert_actions = distinct reverting_rev_id among revert_links "
            "with within_followup and by_other on the page; reverted_editors = distinct author_key "
            "among those links; edits = non-bot history revisions on the page (from revisions, "
            f"with $lookup on page.id). Pages need edits >= {config.CONTESTED_MIN_EDITS} and "
            f"reverted_editors >= {config.CONTESTED_MIN_EDITORS}. score = revert_actions / edits "
            "(a float). Order: score desc, revert_actions desc, edits desc, page_id asc. "
            f"contested = revert_actions >= {config.CONTESTED_MIN_ACTIONS} and score >= "
            f"{config.CONTESTED_MIN_SCORE}. It starts from revert_links, because only pages "
            "with reverts can qualify, and the $lookup then uses the {page.id, ts} index."
            + _how_to(config.COL_REVERT_LINKS))
    return {"collection": config.COL_REVERT_LINKS, "description": desc, "pipeline": pipeline}


def _lag_label_expr(field: str) -> dict:
    return {"$cond": [{"$eq": [field, config.LAG_DEFAULT_BUCKET]}, config.LAG_DEFAULT_BUCKET,
                      {"$arrayElemAt": [config.LAG_LABELS,
                                        {"$indexOfArray": [config.LAG_GRID_S, field]}]}]}


def q3_time_to_revert() -> dict:
    """Spec 3.3: distribution of the time to revert T ($bucket on the lag grid), by cohort.

    Three series: history (T <= 20 d), live (T <= 4 d) and history_4d (the history
    links with T <= 4 d, shares re-normalised), so history and live can also be
    compared on the same 4-day horizon.
    """
    series = {H: {"cohort": H}, L: {"cohort": L},
              H_COMMON: {"cohort": H, "T_s": {"$lte": config.LIVE_FOLLOWUP_S}}}
    facet = {name: [{"$match": m},
                    {"$bucket": {"groupBy": "$T_s", "boundaries": config.LAG_GRID_S,
                                 "default": config.LAG_DEFAULT_BUCKET,
                                 "output": {"n": {"$sum": 1}}}}] for name, m in series.items()}
    pipeline = [
        {"$match": {"cohort": {"$in": [H, L]}, "within_followup": True}},
        {"$facet": facet},
        {"$project": {"rows": {"$concatArrays": [
            {"$map": {"input": f"${name}", "in": {"cohort": name, "bucket_lower_s": "$$this._id",
                                                   "n": "$$this.n"}}} for name in series]}}},
        {"$unwind": "$rows"},
        {"$replaceRoot": {"newRoot": "$rows"}},
        {"$setWindowFields": {"partitionBy": "$cohort", "sortBy": {"bucket_lower_s": 1},
                              "output": {
                                  "total": {"$sum": "$n",
                                            "window": {"documents": ["unbounded", "unbounded"]}},
                                  "cum_n": {"$sum": "$n",
                                            "window": {"documents": ["unbounded", "current"]}}}}},
        {"$project": {"_id": 0, "cohort": 1, "bucket": _lag_label_expr("$bucket_lower_s"),
                      "bucket_lower_s": 1,
                      # bucket_order 1..11 and bucket_sorted "01 <1 min": Atlas Charts sorts
                      # category labels as text, so the sortable label keeps the right order.
                      "bucket_order": {"$add": [{"$indexOfArray": [config.LAG_GRID_S, "$bucket_lower_s"]}, 1]},
                      "bucket_sorted": {"$concat": [
                          {"$cond": [{"$lt": [{"$add": [{"$indexOfArray": [config.LAG_GRID_S, "$bucket_lower_s"]}, 1]}, 10]}, "0", ""]},
                          {"$toString": {"$add": [{"$indexOfArray": [config.LAG_GRID_S, "$bucket_lower_s"]}, 1]}},
                          " ", _lag_label_expr("$bucket_lower_s")]},
                      "bucket_upper_s": {"$arrayElemAt": [
                          config.LAG_GRID_S,
                          {"$add": [{"$indexOfArray": [config.LAG_GRID_S, "$bucket_lower_s"]}, 1]}]},
                      "n": 1, "share": {"$divide": ["$n", "$total"]},
                      "cum_share": {"$divide": ["$cum_n", "$total"]}}},
        {"$sort": {"cohort": 1, "bucket_lower_s": 1}},
    ]
    desc = ("Mongo Q3 (spec 3.3): the distribution of the time to revert T_s (seconds from the "
            "reverted revision to the reverting revision), for revert_links with within_followup. "
            f"Three series (field cohort): '{H}' = history reverts within "
            f"{config.HISTORY_FOLLOWUP_DAYS} days; '{L}' = live reverts within "
            f"{config.LIVE_FOLLOWUP_DAYS} days; '{H_COMMON}' = the history reverts with T_s <= "
            f"{config.LIVE_FOLLOWUP_S} s ({config.LIVE_FOLLOWUP_DAYS} days), with the shares "
            f"computed again on that smaller total. Compare '{L}' with '{H_COMMON}' (the same "
            f"{config.LIVE_FOLLOWUP_DAYS}-day horizon), not with '{H}'. The live T is also cut "
            f"by the capture until {config.LIVE_FINAL_AFTER.isoformat()} (provisional). One "
            "$bucket per series inside a $facet, with the lag grid of config.py as boundaries "
            f"[lower, upper). The default bucket '{config.LAG_DEFAULT_BUCKET}' must stay empty "
            "(run_mongo.py asserts this). Output: cohort (series), bucket label, bucket_lower_s, "
            "bucket_upper_s, n, share of the series, cumulative share. Empty buckets are not "
            "listed." + _how_to(config.COL_REVERT_LINKS))
    return {"collection": config.COL_REVERT_LINKS, "description": desc, "pipeline": pipeline}


def _share_by_total(count_field: str) -> list[dict]:
    return [{"$setWindowFields": {"output": {"total": {"$sum": f"${count_field}"}}}},
            {"$addFields": {"share": {"$divide": [f"${count_field}", "$total"]}}},
            {"$project": {"total": 0}}]


def q4_bot_vs_human() -> dict:
    """Spec 3.4: bot vs human share of reverts made and received, plus edit revert rates."""
    made = [
        {"$group": {"_id": {"kind": "$reverter_kind", "rev": "$reverting_rev_id"},
                    "links": {"$sum": 1}}},
        {"$group": {"_id": "$_id.kind", "revert_actions": {"$sum": 1},
                    "reverted_revisions": {"$sum": "$links"}}},
        {"$project": {"_id": 0, "kind": "$_id", "revert_actions": 1, "reverted_revisions": 1}},
        *_share_by_total("revert_actions"),
        {"$sort": {"revert_actions": -1, "kind": 1}},
    ]
    received = [
        {"$group": {"_id": "$author_kind", "reverted_revisions": {"$sum": 1},
                    "rev_actions": {"$addToSet": "$reverting_rev_id"}}},
        {"$project": {"_id": 0, "kind": "$_id", "reverted_revisions": 1,
                      "revert_actions": {"$size": "$rev_actions"}}},
        *_share_by_total("reverted_revisions"),
        {"$sort": {"reverted_revisions": -1, "kind": 1}},
    ]
    rate = [
        {"$limit": 1},
        {"$lookup": {"from": config.COL_REVISIONS, "pipeline": [
            {"$match": {"cohort": H}},
            {"$group": {"_id": {"$cond": ["$user.is_bot", "bot", "human"]},
                        "edits": {"$sum": 1},
                        "reverted": {"$sum": {"$cond": ["$history.reverted", 1, 0]}},
                        "reverted_by_other": {"$sum": {"$cond": [
                            {"$and": ["$history.reverted", "$history.reverted_by_other"]}, 1, 0]}}}},
            {"$project": {"_id": 0, "kind": "$_id", "edits": 1, "reverted": 1,
                          "reverted_by_other": 1,
                          "revert_rate": {"$divide": ["$reverted", "$edits"]},
                          "revert_rate_by_other": {"$divide": ["$reverted_by_other", "$edits"]}}},
            {"$sort": {"kind": 1}}], "as": "rates"}},
        {"$unwind": "$rates"},
        {"$replaceRoot": {"newRoot": "$rates"}},
    ]
    pipeline = [
        {"$match": {"cohort": H, "within_followup": True, "by_other": True}},
        {"$facet": {"made_by_reverter_kind": made, "received_by_author_kind": received,
                    "edit_revert_rate": rate}},
    ]
    desc = ("Mongo Q4 (spec 3.4): bot vs human share of reverts in the history cohort, with one "
            "$facet. Input: revert_links with within_followup and by_other (self-reverts removed). "
            "made_by_reverter_kind: revert actions (distinct reverting_rev_id) made by each "
            "reverter kind, and their share. received_by_author_kind: reverted revisions by "
            "author kind, and their share. edit_revert_rate: from revisions (an uncorrelated "
            "$lookup), the revert rate of bot edits vs human edits (human = not a bot, so it "
            f"includes the few 'unknown' editors); reverted = history.reverted (within "
            f"{config.HISTORY_FOLLOWUP_DAYS} days, any reverter) and reverted_by_other. "
            "The result is one document with three arrays." + _how_to(config.COL_REVERT_LINKS))
    return {"collection": config.COL_REVERT_LINKS, "description": desc, "pipeline": pipeline}


def _q5_prepared(cohorts: list[str], extra_match: dict | None = None,
                 extra_project: dict | None = None) -> list[dict]:
    """Shared first stages of Q5 and the risk deciles: T, K and the page activity."""
    is_live = {"$eq": ["$cohort", L]}
    prev_hour = {"$dateToString": {
        "date": {"$dateSubtract": {"startDate": "$live.seen_ts", "unit": "hour", "amount": 1}},
        "format": "%Y-%m-%dT%H", "timezone": "UTC"}}
    return [
        {"$match": {"cohort": {"$in": cohorts}, **(extra_match or {})}},
        _revert_link_lookup("link"),
        {"$addFields": {"prev_hour_key": {"$cond": [
            is_live, {"$concat": [{"$toString": "$page.id"}, ":", prev_hour]}, None]}}},
        {"$lookup": {"from": config.COL_PAGE_HOUR, "localField": "prev_hour_key",
                     "foreignField": "_id", "as": "prev_hour"}},
        {"$project": {"_id": 0, "cohort": 1, "user_kind": "$user.kind",
                      "risk": "$live.revert_risk",
                      "T": {"$first": "$link.T_s"}, "K": {"$first": "$link.K_s"},
                      # page_hour (speed layer): live only, the clock hour before the edit was seen.
                      "prev_clock_hour": {"$cond": [
                          is_live, {"$ifNull": [{"$first": "$prev_hour.edits_seen"}, 0]}, None]},
                      # The sliding hour [t - 1 h, t), stored on both kinds of documents.
                      "prev_1h": {"$ifNull": ["$live.page_edits_prev_1h",
                                              "$history.page_edits_prev_1h"]},
                      **(extra_project or {})}},
        {"$addFields": {
            "rev_4d": {"$and": [{"$gte": ["$T", 0]}, {"$lte": ["$T", HORIZON_S]}]},
            "known_by": {"$add": ["$T", {"$ifNull": ["$K", 0]}]}}},
    ]


def q5_truth_lag_preview() -> dict:
    """Spec 3.5: how much of the eventual revert label is already known after a wait."""
    waits = list(config.WAIT_POINTS_S.items())
    known_sums = {f"known_{i}": {"$sum": {"$cond": [
        {"$and": ["$rev_4d", {"$lte": ["$known_by", w]}]}, 1, 0]}} for i, (_, w) in enumerate(waits)}
    known_by = [
        {"$addFields": {"kinds": ["$user_kind", "all"]}},
        {"$unwind": "$kinds"},
        {"$group": {"_id": {"cohort": "$cohort", "user_kind": "$kinds"},
                    "n_edits": {"$sum": 1},
                    "n_reverted_4d": {"$sum": {"$cond": ["$rev_4d", 1, 0]}}, **known_sums}},
        {"$match": {"n_reverted_4d": {"$gte": config.RISK_MIN_GROUP_N}}},
        {"$project": {"_id": 0, "cohort": "$_id.cohort", "user_kind": "$_id.user_kind",
                      "n_edits": 1, "n_reverted_4d": 1,
                      "waits": [{"wait": label, "wait_s": w, "wait_sorted": f"{i + 1:02d} {label}",
                                 "known": f"$known_{i}"}
                                for i, (label, w) in enumerate(waits)]}},
        {"$unwind": "$waits"},
        {"$project": {"cohort": 1, "user_kind": 1, "wait": "$waits.wait",
                      "wait_s": "$waits.wait_s", "wait_sorted": "$waits.wait_sorted",
                      "n_edits": 1, "n_reverted_4d": 1,
                      "revert_rate_4d": {"$divide": ["$n_reverted_4d", "$n_edits"]},
                      "known": "$waits.known",
                      "share_known": {"$divide": ["$waits.known", "$n_reverted_4d"]}}},
        {"$sort": {"cohort": 1, "user_kind": 1, "wait_s": 1}},
    ]
    edge_of = {"$switch": {"branches": [
        {"case": {"$lt": ["$measure.edits", nxt]}, "then": e}
        for e, nxt in zip(ACTIVITY_EDGES[:-1], ACTIVITY_EDGES[1:])],
        "default": ACTIVITY_EDGES[-1]}}
    sliding = {"source": "prev_1h", "edits": "$prev_1h"}
    activity = [
        # Live documents get two measures: page_hour (speed layer) and the sliding hour.
        # History documents only have the sliding hour (no page_hour for September).
        {"$project": {"cohort": 1, "rev_4d": 1, "measure": {"$cond": [
            {"$eq": ["$cohort", L]},
            [{"source": "page_hour", "edits": "$prev_clock_hour"}, sliding], [sliding]]}}},
        {"$unwind": "$measure"},
        {"$group": {"_id": {"cohort": "$cohort", "source": "$measure.source", "edge": edge_of},
                    "n_edits": {"$sum": 1},
                    "n_reverted_4d": {"$sum": {"$cond": ["$rev_4d", 1, 0]}}}},
        {"$match": {"n_edits": {"$gte": config.RISK_MIN_GROUP_N}}},
        {"$project": {"_id": 0, "cohort": "$_id.cohort", "source": "$_id.source",
                      "prev_hour_edits": {"$arrayElemAt": [
                          ACTIVITY_LABELS, {"$indexOfArray": [ACTIVITY_EDGES, "$_id.edge"]}]},
                      "prev_hour_edits_from": "$_id.edge",
                      "n_edits": 1, "n_reverted_4d": 1,
                      "revert_rate_4d": {"$divide": ["$n_reverted_4d", "$n_edits"]}}},
        {"$sort": {"cohort": 1, "source": 1, "prev_hour_edits_from": 1}},
    ]
    pipeline = _q5_prepared([H, L]) + [{"$facet": {"known_by": known_by, "activity": activity}}]
    desc = ("Mongo Q5 (spec 3.5), the truth-lag preview: live-stream signals vs the eventual "
            "revert label. It starts from revisions (both cohorts). An equality $lookup on "
            "rev_id = revert_links.reverted_rev_id (same cohort) gives T (time to revert) and, "
            "for the live cohort, K (stream delay). Eventual revert = T <= "
            f"{HORIZON_S} s ({config.LIVE_FOLLOWUP_DAYS} days, the horizon both cohorts share; "
            "self-reverts count). known_by = T + K for live (when the stream showed the revert) "
            "and T for history (the dump has no stream delay). Part 'known_by': for each cohort "
            "and user kind (and 'all'), the share of eventual reverts already known after each "
            f"wait {list(config.WAIT_POINTS_S)}; groups with fewer than {config.RISK_MIN_GROUP_N} "
            "eventual reverts are dropped. Part 'activity': the revert rate by the page's edits "
            "in the hour before the edit, with two measures (column source). source = "
            "'page_hour', live only: a second $lookup reads page_hour (the speed layer) for the "
            "clock hour before the edit was seen; the edits earlier in the same clock hour are "
            "not in it. source = 'prev_1h', both cohorts: the sliding hour [t - 1 h, t) stored "
            "in the document (history.page_edits_prev_1h from the dump; live.page_edits_prev_1h "
            "from the stream). page_hour does not exist for September, so compare the cohorts "
            "with 'prev_1h' only. Groups with fewer than "
            f"{config.RISK_MIN_GROUP_N} edits are dropped. The "
            f"stream labels of the live cohort are provisional until {config.LIVE_FINAL_AFTER.isoformat()}. Atlas "
            "holds the history cohort only." + _how_to(config.COL_REVISIONS))
    return {"collection": config.COL_REVISIONS, "description": desc, "pipeline": pipeline}


def compare_mutual_reverts() -> dict:
    """Spec 5: mutual-revert pairs (a < b) per page, with a self-$lookup."""
    base = {"cohort": H, "within_followup": True, "by_other": True}
    pipeline = [
        {"$match": {**base, "reverter_key": {"$ne": None}, "author_key": {"$ne": None}}},
        {"$group": {"_id": {"a": "$reverter_key", "b": "$author_key", "page_id": "$page_id"},
                    "actions": {"$addToSet": "$reverting_rev_id"}}},
        # Each unordered pair is looked up once, from the side where a < b.
        {"$match": {"$expr": {"$lt": ["$_id.a", "$_id.b"]}}},
        {"$lookup": {"from": config.COL_REVERT_LINKS, "localField": "_id.page_id",
                     "foreignField": "page_id", "let": {"a": "$_id.a", "b": "$_id.b"},
                     "pipeline": [
                         {"$match": {**base, "$expr": {"$and": [
                             {"$eq": ["$reverter_key", "$$b"]}, {"$eq": ["$author_key", "$$a"]}]}}},
                         {"$group": {"_id": None, "actions": {"$addToSet": "$reverting_rev_id"}}}],
                     "as": "back"}},
        {"$unwind": "$back"},
        {"$project": {"_id": 0, "page_id": "$_id.page_id", "a": "$_id.a", "b": "$_id.b",
                      "a_reverted_b": {"$size": "$actions"},
                      "b_reverted_a": {"$size": "$back.actions"}}},
        {"$sort": {"page_id": 1, "a": 1, "b": 1}},
    ]
    desc = ("Mutual reverts (spec 5, the comparison query; DATA_MODEL.md section 7): editor a "
            "reverted b AND b reverted a on the SAME page. Input: history revert_links with "
            "within_followup and by_other (both keys not null). $group makes the triples "
            "(reverter_key, author_key, page_id) with the distinct reverting revisions; a "
            "self-$lookup on revert_links (same page, roles swapped) finds the reverse "
            "direction. One row per page and unordered pair (a < b by key): page_id, a, b, "
            "a_reverted_b and b_reverted_a (distinct revert actions in each direction). "
            "Ordered by page_id, a, b. The output shows editor keys: results/ files replace "
            "human keys with pseudonyms." + _how_to(config.COL_REVERT_LINKS))
    return {"collection": config.COL_REVERT_LINKS, "description": desc, "pipeline": pipeline}


