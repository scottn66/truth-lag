def pandas_known_by(cohorts: list[str]) -> pd.DataFrame:
    rows = []
    for c in cohorts:
        rev = pd.read_parquet(bd.TABLE_FILES[f"{c}_revisions"], columns=["rev_id", "user_kind"])
        lk = _links(c)[["reverted_rev_id", "T_s", "K_s"]]
        m = rev.merge(lk, left_on="rev_id", right_on="reverted_rev_id", how="left")
        m["rev_4d"] = (m["T_s"] >= 0) & (m["T_s"] <= HORIZON_S)
        m["known_by"] = m["T_s"] + m["K_s"].fillna(0)
        for kind, g in list(m.groupby("user_kind")) + [("all", m)]:
            n4 = int(g["rev_4d"].sum())
            if n4 < config.RISK_MIN_GROUP_N:
                continue
            for label, w in config.WAIT_POINTS_S.items():
                k = int((g["rev_4d"] & (g["known_by"] <= w)).sum())
                rows.append({"cohort": c, "user_kind": kind, "wait_s": w, "n_edits": len(g),
                             "n_reverted_4d": n4, "known": k, "share_known": k / n4})
    return pd.DataFrame(rows)


def check_q5(mongo: pd.DataFrame, cohorts: list[str]) -> dict:
    pdf = pandas_known_by(cohorts)
    key = ["cohort", "user_kind", "wait_s"]
    m = mongo.merge(pdf, on=key, how="outer", suffixes=("_mongo", "_pandas"), indicator=True)
    same = ((m["_merge"] == "both").all()
            and (m["n_reverted_4d_mongo"] == m["n_reverted_4d_pandas"]).all()
            and (m["known_mongo"] == m["known_pandas"]).all()
            and (m["n_edits_mongo"] == m["n_edits_pandas"]).all())
    print(f"Q5 check: share of eventual reverts (T <= {config.LIVE_FOLLOWUP_DAYS} d) known "
          f"within {config.LIVE_FOLLOWUP_DAYS} d, Mongo | pandas")
    at = m[m["wait_s"] == HORIZON_S].sort_values(["cohort", "user_kind"])
    for _, r in at.iterrows():
        print(f"  {r['cohort']:8s} {r['user_kind']:11s} {r['known_mongo']:>6.0f}/{r['n_reverted_4d_mongo']:<6.0f}"
              f" = {r['share_known_mongo']:.6f} | {r['known_pandas']:>6.0f}/{r['n_reverted_4d_pandas']:<6.0f}"
              f" = {r['share_known_pandas']:.6f}")
    return {"name": "Q5 known-by shares = pandas (every cohort, kind and wait)", "ok": bool(same)}


def check_q1(mongo: pd.DataFrame, cohorts: list[str]) -> dict:
    parts = []
    for c in cohorts:
        rev = pd.read_parquet(bd.TABLE_FILES[f"{c}_revisions"],
                              columns=["rev_id", "hour_utc", "user_kind"] + (["reverted"] if c == H else []))
        if c == L:
            lk = _links(L)
            rev["reverted"] = rev["rev_id"].isin(lk.loc[lk["within_followup"], "reverted_rev_id"])
        g = rev.groupby(["hour_utc", "user_kind"]).agg(edits=("rev_id", "size"),
                                                       reverted=("reverted", "sum")).reset_index()
        g.insert(0, "cohort", c)
        parts.append(g)
    pdf = pd.concat(parts, ignore_index=True)
    key = ["cohort", "hour_utc", "user_kind"]
    m = mongo.merge(pdf, on=key, how="outer", suffixes=("_m", "_p"), indicator=True)
    ok = (m["_merge"] == "both").all() and (m["edits_m"] == m["edits_p"]).all() \
        and (m["reverted_m"] == m["reverted_p"]).all()
    tot = mongo.groupby("cohort")[["edits", "reverted"]].sum()
    print("Q1 check: totals per cohort (Mongo):",
          "; ".join(f"{c}: {r.edits:,} edits, {r.reverted:,} reverted" for c, r in tot.iterrows()))
    return {"name": "Q1 = pandas (every cohort x hour x user kind)", "ok": bool(ok)}


def default_bucket_empty(q3: pd.DataFrame) -> bool:
    """True when no Mongo Q3 row is in the $bucket default bucket (T past the last edge)."""
    return not (q3["bucket_lower_s"].astype(str) == config.LAG_DEFAULT_BUCKET).any()


def check_q3(mongo: pd.DataFrame, cohorts: list[str]) -> list[dict]:
    checks = [{"name": f"Q3 default bucket '{config.LAG_DEFAULT_BUCKET}' is empty",
               "ok": default_bucket_empty(mongo)}]
    ok = True
    series = [(c, c, None) for c in cohorts]
    if H in cohorts:
        series.append((H_COMMON, H, config.LIVE_FOLLOWUP_S))
    for name, c, cap in series:
        lk = _links(c)
        lk = lk[lk["within_followup"]]
        if cap is not None:
            lk = lk[lk["T_s"] <= cap]
        cut = pd.cut(lk["T_s"], bins=config.LAG_GRID_S, right=False, labels=config.LAG_GRID_S[:-1])
        want = cut.value_counts().loc[lambda s: s > 0].sort_index()
        got = mongo[mongo["cohort"] == name].set_index("bucket_lower_s")["n"]
        ok &= {int(k): int(v) for k, v in want.items()} == {int(k): int(v) for k, v in got.items()}
    checks.append({"name": f"Q3 bucket counts = pandas ({', '.join(n for n, _, _ in series)})",
                   "ok": bool(ok)})
    return checks


def check_deciles(rows: list[dict]) -> dict:
    """Each risk group: n, reverts within 4 d and the exact median T, against pandas."""
    rev = pd.read_parquet(bd.TABLE_FILES["live_revisions"],
                          columns=["rev_id", "revert_risk", "parent_id"])
    lk = _links(L)[["reverted_rev_id", "T_s"]]
    m = rev.merge(lk, left_on="rev_id", right_on="reverted_rev_id", how="left")
    ok = True
    last = max((r["decile"] for r in rows if r["decile"] is not None), default=None)
    for r in rows:
        if r["decile"] is None:
            sel = m["revert_risk"].isna()
        elif r["decile"] == last:          # $bucketAuto: the last group includes its max
            sel = (m["revert_risk"] >= r["risk_min"]) & (m["revert_risk"] <= r["risk_max"])
        else:
            sel = (m["revert_risk"] >= r["risk_min"]) & (m["revert_risk"] < r["risk_max"])
        g = m[sel]
        t = g["T_s"][(g["T_s"] >= 0) & (g["T_s"] <= HORIZON_S)]
        med = None if t.empty else float(t.median())
        creations = int((g["parent_id"].fillna(0) == 0).sum())
        same = (int(sel.sum()) == r["n"] and len(t) == r["n_reverted_4d"]
                and creations == r["n_page_creations"]
                and med == (None if r["median_T_s"] is None else float(r["median_T_s"])))
        ok &= same
        print(f"  {r['group']:10s} n {r['n']:>6,} reverted {r['n_reverted_4d']:>5,} "
              f"page creations {r['n_page_creations']:>5,} "
              f"median T {r['median_T_s']} s {'' if same else '<-- DIFFERENT from pandas'}")
    return {"name": "Q5 risk deciles = pandas (n, reverts, page creations, exact median T)",
            "ok": bool(ok)}


def pandas_mutual(public_keys: bool = False) -> pd.DataFrame:
    """The mutual pairs from the Parquet links. public_keys=True first applies the Atlas
    rule (load_mongo._pseudonymize_link: human keys become aliases, bot keys stay)."""
    lk = _links(H)
    lk = lk[(lk["cohort"] == H) & lk["within_followup"] & lk["by_other"]
            & lk["reverter_key"].notna() & lk["author_key"].notna()]
    if public_keys:
        from load_mongo import _pseudonymize_link
        n_hex = bd.alias_length(bd.all_editor_keys())
        lk = pd.DataFrame([_pseudonymize_link(r, n_hex) for r in lk.to_dict("records")],
                          columns=lk.columns)
    t = lk.groupby(["reverter_key", "author_key", "page_id"])["reverting_rev_id"].nunique()
    t = t.rename("n").reset_index()
    fwd = t[t["reverter_key"] < t["author_key"]]
    back = t.rename(columns={"reverter_key": "author_key", "author_key": "reverter_key", "n": "n_back"})
    m = fwd.merge(back, on=["reverter_key", "author_key", "page_id"])
    m = m.rename(columns={"reverter_key": "a", "author_key": "b", "n": "a_reverted_b",
                          "n_back": "b_reverted_a"})
    return m.sort_values(["page_id", "a", "b"]).reset_index(drop=True)[
        ["page_id", "a", "b", "a_reverted_b", "b_reverted_a"]]


def _unordered_pairs(df: pd.DataFrame) -> list:
    """(page_id, {(a, a_reverted_b), (b, b_reverted_a)}) rows, sorted: no a < b order."""
    rows = [(int(r.page_id),
             tuple(sorted([(r.a, int(r.a_reverted_b)), (r.b, int(r.b_reverted_a))])))
            for r in df.itertuples(index=False)]
    return sorted(rows)


def check_mutual(mongo: pd.DataFrame, aliased: bool = False) -> dict:
    """Local: the full ordered list must equal pandas. Atlas (aliased=True): the keys are
    aliases, so the a < b order differs; compare page, editor pair and counts without order."""
    cols = ["page_id", "a", "b", "a_reverted_b", "b_reverted_a"]
    mongo = mongo if len(mongo) else pd.DataFrame(columns=cols)
    pdf = pandas_mutual(public_keys=aliased)
    print(f"mutual pairs: Mongo {len(mongo):,} rows, pandas {len(pdf):,} rows")
    if aliased:
        return {"name": "mutual pairs = pandas (page, editor pair and counts; no order)",
                "ok": _unordered_pairs(mongo[cols]) == _unordered_pairs(pdf[cols])}
    a = [tuple(r) for r in mongo[cols].itertuples(index=False)]
    b = [tuple(r) for r in pdf[cols].itertuples(index=False)]
    return {"name": "mutual pairs = pandas (full ordered list)", "ok": a == b}


_KEY_PATTERN = r"^(u:\d+|t:.+)$"      # config.editor_key: 'u:<user_id>' or 't:<name>'


def check_no_editor_identity(tables: dict[str, pd.DataFrame], bots: set | None = None) -> dict:
    """No result file may show an editor key, and editor columns show aliases or bot names.

    tables = the tables that are written to results/ (mutual_raw is not written).
    bots = the bot names that may be shown (default: every bot in the cohort tables).
    """
    if bots is None:
        info, _ = editor_names()
        bots = {name for kind, name in info.values() if kind == "bot" and name}
    bad = []
    for name, df in tables.items():
        for col in df.columns:
            v = df[col]
            if v.dtype != object and not pd.api.types.is_string_dtype(v):
                continue
            text = v.dropna().astype(str)
            if col != "page_title" and text.str.match(_KEY_PATTERN).any():
                bad.append(f"{name}.{col}: editor key")
            if col.startswith("editor_"):
                ok = text.str.match(r"^editor_[0-9a-f]+$") | text.isin(bots)
                if not ok.all():
                    bad.append(f"{name}.{col}: {int((~ok).sum())} values are not aliases "
                               "or bot names")
    for b in bad:
        print(f"  NAME CHECK: {b}")
    return {"name": "no editor key or human name in the result files", "ok": not bad}


