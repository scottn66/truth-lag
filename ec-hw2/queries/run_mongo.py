def _revert_link_lookup(as_field: str, extra_match: dict | None = None,
                        fields=("T_s", "K_s")) -> dict:
    """Equality $lookup from revisions.rev_id to revert_links.reverted_rev_id, same cohort."""
    match = {"$expr": {"$eq": ["$cohort", "$$c"]}}
    if extra_match:
        match.update(extra_match)
    return {"$lookup": {"from": config.COL_REVERT_LINKS, "localField": "rev_id",
                        "foreignField": "reverted_rev_id", "let": {"c": "$cohort"},
                        "pipeline": [{"$match": match},
                                     {"$project": {"_id": 0, **{f: 1 for f in fields}}}],
                        "as": as_field}}


